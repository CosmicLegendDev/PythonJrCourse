n1 = "Guhan"
age = 12
grade = 7

# My name is Guhan, and am 12 years old and studying grade 7.
# using format method.
print("My name is {}, and am {} years old and studying grade {}.".format(n1, age, grade))

# using f-strings.
print(f"My name is {n1}, and am {age} years old, and studying grade {grade}.")

# using concatination operator.
print("My name is " + n1 + ", and am " + str(age) + " years old.")

